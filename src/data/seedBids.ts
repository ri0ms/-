export function generateSeedBids(): BidItem[] {
  return RAW_SEED_BIDS.map((raw) => {
    const dDay = computeDDay(raw.deadlineDate);
    const partialItem = {
      id: `${raw.bidNo}-${raw.bidSeq}`,
      bidNo: raw.bidNo,
      bidSeq: raw.bidSeq,
      title: raw.title,
      agency: raw.agency,
      agencyGroup: raw.agency.includes('청') || raw.agency.includes('구청') || raw.agency.includes('세관') || raw.agency.includes('어촌어항공단') || raw.agency.includes('도로교통공단')
        ? ('기존실적' as const)
        : raw.agency.includes('육군') || raw.agency.includes('해군') || raw.agency.includes('공군') || raw.agency.includes('국방') || raw.agency.includes('철도') || raw.agency.includes('항만') || raw.agency.includes('공항') || raw.agency.includes('방위사업청') || raw.agency.includes('교통안전공단') || raw.agency.includes('경찰')
        ? ('확장목표' as const)
        : ('기타' as const),
      field: raw.field,
      estimatedPrice: raw.estimatedPrice,
      contractMethod: raw.contractMethod,
      publishDate: raw.publishDate,
      deadlineDate: raw.deadlineDate,
      dDay,
      matchingKeywords: raw.matchingKeywords,
      g2bUrl: raw.g2bUrl || `https://www.g2b.go.kr:8081/ep/invitation/publish/bidInfoDtl.do?bidno=${raw.bidNo}&bidseq=${raw.bidSeq}`,
      isNew: raw.isNew ?? false,
      isViewed: false,
      isBookmarked: false,
      feedback: 'NONE' as const,
      dataSource: 'SEED_DEMO' as const,
    };

    const scoringResult = calculateBidScore(partialItem, DEFAULT_CONFIG);

    return {
      ...partialItem,
      score: scoringResult.score,
      grade: scoringResult.grade,
      scoreBreakdown: scoringResult.scoreBreakdown,
    };
  });
}
